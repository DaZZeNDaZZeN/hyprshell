btn = mix(bg, text, 0.07)
light = mix(btn, "#ffffff", 0.3)
mid = mix(btn, "#000000", 0.2)
dk = mix(btn, "#000000", 0.4)
c = lambda h: ",".join(str(x) for x in rgb(h))
inact_fg = c(sub)
pos_fg = "158,206,106"
neu_fg = "224,175,104"
neg_fg = "247,118,142"

